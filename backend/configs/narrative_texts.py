# 获取突破叙事文本的辅助函数（P1 使用，P0 先定义）
def get_breakthrough_narrative(from_realm: str, to_realm: str, success: bool) -> str | None:
    """
    根据突破的前后境界，返回对应的叙事文本。
    P0 阶段暂不集成，预留接口。
    """
    key = f"{from_realm}_{to_realm}"
    if key not in BREAKTHROUGH_NARRATIVES:
        return None
    pool_key = "success" if success else "failure"
    pool = BREAKTHROUGH_NARRATIVES[key].get(pool_key, [])
    return random.choice(pool) if pool else None
