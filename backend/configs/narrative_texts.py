# 获取修炼叙事文本的辅助函数
def get_train_narrative(realm: str) -> str | None:
    """
    根据玩家境界，从对应的叙事文本池中随机抽取一条。
    返回 None 如果没有对应境界的文本池。
    """
    # 根据境界名称匹配对应的文本池
    for key in TRAIN_NARRATIVES:
        if key in realm:
            pool = TRAIN_NARRATIVES[key]
            return random.choice(pool) if pool else None
    return None


